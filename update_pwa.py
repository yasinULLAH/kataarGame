#!/usr/bin/env python3
"""
Katar Game — PWA cache updater
================================
Run this file (double-click it, or `python update_pwa.py`) after making ANY
change to the game. It will:

  1. Scan the project folder and collect every file the app needs.
  2. Compute a content hash so the cache version changes only when files change.
  3. Regenerate `sw.js` with a fresh cache name + full asset list.
  4. Bump the `sw.js?v=...` version in `index.html` so browsers fetch the new
     service worker immediately.
  5. (Optionally) commit and push to GitHub so the update goes live.

It uses only the Python standard library — no dependencies to install.
"""

import os
import re
import hashlib
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))

# Names / extensions that must NEVER be pre-cached.
EXCLUDE_NAMES = {
    "sw.js",                 # the browser manages the SW; don't cache it inside itself
    "update_pwa.py",         # this script
    "logo.png",              # source logo, not used at runtime
    "multiplayer info.txt",  # dev note
    "favicon.ico",
    ".gitattributes",
}
EXCLUDE_DIRS = {".git", "__pycache__"}
EXCLUDE_EXTS = {".py", ".pyw", ".pyc", ".txt", ".md", ".log", ".bak", ".zip"}

# The service-worker template. __CACHE_NAME__ and __ASSETS__ are replaced.
SW_TEMPLATE = """// Auto-generated by update_pwa.py — do not edit by hand.
const CACHE_NAME = '__CACHE_NAME__';
const ASSETS = [
__ASSETS__
];

// Install: pre-cache every local asset so the whole app works offline.
self.addEventListener('install', (e) => {
  e.waitUntil(
    caches.open(CACHE_NAME)
      .then((c) => c.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
});

// Activate: remove old caches and take control immediately.
self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});

// Fetch:
//  - navigations: network-first (online users always get the latest build),
//    falling back to the cached index.html when offline.
//  - other assets: cache-first (instant + offline-safe), with background refresh.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;

  if (req.mode === 'navigate') {
    e.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((c) => c.put('./', copy));
          return res;
        })
        .catch(() => caches.match('./index.html').then((r) => r || caches.match('./')))
    );
    return;
  }

  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return; // ignore cross-origin (none should remain)

  e.respondWith(
    caches.match(req).then((cached) => {
      if (cached) return cached;
      return fetch(req).then((res) => {
        if (res && res.status === 200) {
          const copy = res.clone();
          caches.open(CACHE_NAME).then((c) => c.put(req, copy));
        }
        return res;
      });
    })
  );
});
"""


def collect_assets():
    """Return a sorted list of './relative/path' entries to pre-cache."""
    assets = []
    for dirpath, dirnames, filenames in os.walk(ROOT):
        dirnames[:] = [
            d for d in dirnames
            if d not in EXCLUDE_DIRS and not d.startswith(".")
        ]
        for fn in filenames:
            if fn.startswith(".") or fn in EXCLUDE_NAMES:
                continue
            ext = os.path.splitext(fn)[1].lower()
            if ext in EXCLUDE_EXTS:
                continue
            rel = os.path.relpath(os.path.join(dirpath, fn), ROOT).replace("\\", "/")
            assets.append("./" + rel)
    return sorted(assets)


def compute_hash(assets):
    """Content-based hash over all assets (path + bytes)."""
    h = hashlib.sha256()
    for a in assets:
        h.update(a.encode("utf-8"))
        path = os.path.join(ROOT, a[2:])
        if os.path.isfile(path):
            try:
                with open(path, "rb") as f:
                    h.update(f.read())
            except OSError:
                pass
    return h.hexdigest()[:10]


def write_sw(assets, version):
    assets_block = ",\n".join(f"  '{a}'" for a in assets)
    sw = SW_TEMPLATE.replace("__CACHE_NAME__", f"katar-pwa-{version}")
    sw = sw.replace("__ASSETS__", assets_block)
    with open(os.path.join(ROOT, "sw.js"), "w", encoding="utf-8", newline="\n") as f:
        f.write(sw)


def bump_index_version(version):
    index_path = os.path.join(ROOT, "index.html")
    with open(index_path, "r", encoding="utf-8") as f:
        content = f.read()
    new_content, n = re.subn(
        r"sw\.js(\?v[^'\"]*)?",
        f"sw.js?v={version}",
        content,
    )
    with open(index_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(new_content)
    return n


def main():
    print("=" * 62)
    print("  Katar Game - PWA cache updater")
    print("=" * 62)

    assets = collect_assets()
    version = compute_hash(assets)
    write_sw(assets, version)
    regs = bump_index_version(version)

    print(f"  Assets pre-cached      : {len(assets)}")
    print(f"  New cache version      : {version}")
    print(f"  Wrote sw.js            : katar-pwa-{version}")
    print(f"  index.html SW version  : {regs} registration(s) bumped")
    print("-" * 62)

    # Offer to commit + push if this is a git repo.
    is_git = os.path.isdir(os.path.join(ROOT, ".git"))
    if is_git:
        print("  This looks like a git repository.")
        choice = input("  Commit & push to GitHub now? [y/N] ").strip().lower()
        if choice == "y":
            print("  -> git add -A ...")
            subprocess.run(["git", "add", "-A"], cwd=ROOT)
            print("  -> git commit ...")
            subprocess.run(
                ["git", "commit", "-m", f"PWA update (cache v{version})"],
                cwd=ROOT,
            )
            print("  -> git push ...")
            subprocess.run(["git", "push"], cwd=ROOT)
            print("  Pushed! GitHub Pages will publish the update shortly.")
    else:
        print("  (Not a git repo - upload the files to your host manually.)")

    print("=" * 62)
    input("\n  Done. Press Enter to close...")


if __name__ == "__main__":
    try:
        main()
    except Exception:
        import traceback
        traceback.print_exc()
        input("\n  An error occurred. Press Enter to close...")
